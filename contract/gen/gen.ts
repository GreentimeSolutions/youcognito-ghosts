import { COSMETICS, body, hat, shades, aura, trail, prop } from "./gw.ts";
import { writeFileSync } from "node:fs";
const pal: string[] = []; const layers: number[][] = []; const names: string[] = [];
const rec = (fn: (p: any) => void, name: string) => {
  const r: number[] = [];
  fn((x: number, y: number, w: number, h: number, c: string) => {
    c = c.toLowerCase(); let i = pal.indexOf(c); if (i < 0) { pal.push(c); i = pal.length - 1; }
    if (x < 0 || y < 0 || w <= 0 || h <= 0) throw new Error("bad rect " + name);
    r.push(x, y, w, h, i);
  });
  layers.push(r); names.push(name);
};
const cat = (k: string) => COSMETICS.filter((c) => c.cat === k);
const counts: number[] = [];
// Slot order in contract: 0 hat,1 shades,2 skin,3 aura,4 trail,5 prop
for (const c of cat("aura")) rec((p) => aura(p, c, 0), c.id);
for (const c of cat("trail")) rec((p) => trail(p, c, 0), c.id);
rec((p) => body(p, undefined, 0), "body-default");
for (const c of cat("skin")) rec((p) => body(p, c, 0), c.id);
rec((p) => { p(12, 14, 2, 2, "#1b1b2f"); p(18, 14, 2, 2, "#1b1b2f"); }, "eyes");
for (const c of cat("shades")) rec((p) => shades(p, c, 0), c.id);
for (const c of cat("hat")) rec((p) => hat(p, c), c.id);
for (const c of cat("prop")) rec((p) => prop(p, c), c.id);
let data: number[] = []; const off: number[] = [];
for (const l of layers) { off.push(data.length); data.push(...l); } off.push(data.length);
const hex = (a: number[]) => a.map((b) => b.toString(16).padStart(2, "0")).join("");
const offHex = off.map((o) => o.toString(16).padStart(4, "0")).join("");
const palHex = pal.map((c) => c.slice(1)).join("");
const nm = (k: string) => cat(k).map((c) => c.name);
writeFileSync("../src/GhostData.sol", `// SPDX-License-Identifier: MIT
// AUTO-GENERATED by gen/gen.ts from ghost-wardrobe.ts @22c3bca (frame t=0). Do not edit by hand.
pragma solidity 0.8.24;
library GhostData {
    // Layer order: aura[5], trail[5], body[default + 6 skins], eyes, shades[7], hats[9], props[6]
    uint256 internal constant AURA = 0; uint256 internal constant TRAIL = 5; uint256 internal constant BODY = 10;
    uint256 internal constant EYES = 17; uint256 internal constant SHADES = 18; uint256 internal constant HAT = 25; uint256 internal constant PROP = 34;
    uint256 internal constant LAYERS = ${layers.length};
    bytes internal constant PALETTE = hex"${palHex}";
    bytes internal constant OFFSETS = hex"${offHex}";
    bytes internal constant RECTS = hex"${hex(data)}";
}
`);
writeFileSync("../src/names.json", JSON.stringify({ hat: nm("hat"), shades: nm("shades"), skin: nm("skin"), aura: nm("aura"), trail: nm("trail"), prop: nm("prop") }, null, 1));
console.log(layers.length, "layers", data.length, "bytes rects", pal.length, "colors", names.join(","));
